"""Download + install the official participant kit (data, starter kit, docs) into the git-ignored folders.

    python scripts/fetch_kit.py            # skip if already installed
    python scripts/fetch_kit.py --force    # re-download
    python scripts/fetch_kit.py --url https://repteupc.datathon.cat/media/<hash>.zip
    python scripts/fetch_kit.py --zip path/to/paquet_participants_datathon_upc.zip   # use a local copy

Result:  data/train/*.csv   starter_kit/*   docs/official/*   (all git-ignored)
The /media/<hash>.zip URL is generated by the Streamlit site and may change: if the default fails, open
https://repteupc.datathon.cat/ -> tab "Dades del Campus i Starter Kit", click "Descarregar Paquet per als Participants",
read the URL from the browser network log (or save the file) and pass --url / --zip.
Local tooling only (uses urllib) - never import this from agent code.
"""
import argparse
import shutil
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_URL = "https://repteupc.datathon.cat/media/e20750421be841a212d9265e1c8489f1.zip"


def installed() -> bool:
    return (ROOT / "data/train/contador.csv").exists() and (ROOT / "starter_kit/environment.py").exists()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default=DEFAULT_URL)
    ap.add_argument("--zip", help="use an already-downloaded kit ZIP")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()

    if installed() and not a.force:
        print("kit already installed (data/train + starter_kit). Use --force to re-download.")
        return

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        zpath = Path(a.zip) if a.zip else tmp / "kit.zip"
        if not a.zip:
            print(f"downloading {a.url} ...")
            try:
                req = urllib.request.Request(a.url, headers={"User-Agent": "curl/8.0"})
                with urllib.request.urlopen(req, timeout=120) as r, open(zpath, "wb") as f:
                    shutil.copyfileobj(r, f)
            except Exception as e:
                sys.exit(f"download failed ({e}). See the docstring: pass --url or --zip.")
        if not zipfile.is_zipfile(zpath):
            sys.exit(f"{zpath} is not a ZIP file (URL expired?). Pass a fresh --url or --zip.")
        out = tmp / "x"
        with zipfile.ZipFile(zpath) as z:
            for m in z.namelist():                      # refuse path traversal
                if m.startswith("/") or ".." in Path(m).parts:
                    sys.exit(f"unsafe path in ZIP: {m}")
            z.extractall(out)

        for src, dst in (("data/train", "data/train"), ("starter_kit", "starter_kit"), ("docs", "docs/official")):
            (ROOT / dst).mkdir(parents=True, exist_ok=True)
            for f in (out / src).glob("*"):
                if f.is_file():
                    shutil.copy2(f, ROOT / dst / f.name)
        if (out / "README.md").exists():
            (ROOT / "docs/official").mkdir(parents=True, exist_ok=True)
            shutil.copy2(out / "README.md", ROOT / "docs/official/KIT_README.md")

    print("installed:", "OK" if installed() else "INCOMPLETE")
    print("next: python -m sim.evaluate --weeks")


if __name__ == "__main__":
    main()
